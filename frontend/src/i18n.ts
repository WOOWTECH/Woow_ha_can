export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function makeTranslate(language: string): Translate {
  const dict: Record<Key, string> = language.toLowerCase().startsWith("zh") ? zh : en;
  return (key, vars) => {
    let text = dict[key] ?? en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };
}

export function isKey(key: string): key is Key {
  return key in en;
}

export function ago(time: number, t: Translate, now = Date.now() / 1000): string {
  const seconds = Math.max(0, now - time);
  if (seconds < 5) return t("just_now");
  if (seconds < 60) return t("s_ago", { n: Math.floor(seconds) });
  if (seconds < 3600) return t("m_ago", { n: Math.floor(seconds / 60) });
  if (seconds < 86400) return t("h_ago", { n: Math.floor(seconds / 3600) });
  return t("d_ago", { n: Math.floor(seconds / 86400) });
}

export function clock(time: number): string {
  const d = new Date(time * 1000);
  const pad = (n: number, w = 2) => String(n).padStart(w, "0");
  return `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}.${pad(d.getMilliseconds(), 3)}`;
}

/** 0.0123 -> "12.3 ms", 2.5 -> "2.50 s". */
export function duration(seconds: number | null | undefined): string {
  if (seconds == null || !isFinite(seconds)) return "–";
  if (seconds < 1) return `${(seconds * 1000).toFixed(seconds < 0.01 ? 2 : 1)} ms`;
  if (seconds < 100) return `${seconds.toFixed(2)} s`;
  return `${Math.round(seconds)} s`;
}

export function bytes(n: number): string {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / 1024 / 1024).toFixed(1)} MB`;
}

export function percent(v: number | null | undefined): string {
  return v == null ? "–" : `${v.toFixed(v < 10 ? 1 : 0)}%`;
}

/** An error-frame code ("controller:tx_passive") in the user's language. */
export function errorCode(code: string, t: Translate): string {
  const key = `err_${code}`;
  return isKey(key) ? t(key) : code;
}
